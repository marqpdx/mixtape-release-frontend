// W3C relative luminance → pick readable ink color against an accent background.

function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '');
  const n = parseInt(h.length === 3 ? h.split('').map(c => c + c).join('') : h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function linearize(c: number): number {
  const s = c / 255;
  return s <= 0.04045 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
}

function relativeLuminance(hex: string): number {
  const [r, g, b] = hexToRgb(hex).map(linearize);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** Returns '#0e0d0a' (dark) or '#fff7ed' (light) based on luminance of the accent hex. */
export function computeAccentInk(accent: string): string {
  return relativeLuminance(accent) > 0.62 ? '#0e0d0a' : '#fff7ed';
}
